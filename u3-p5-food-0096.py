import pandas as pd
import matplotlib.pyplot as plt
## Samuel Martinez NC 0096
# 4. Leer el archivo CSV
df_food_india = pd.read_csv('indian_food.csv')
print("\n--- DATOS LEÍDOS DESDE CSV, comida india 0096 ---")
print(df_food_india)
print("\n--- Mostrar Nombre comida + ingredientes, comida india 0096 ---")
recipes = df_food_india[['name', 'ingredients']]
print(recipes)
print("\n--- Tiempo de cocinado mostrandr 10 registros con head, comida india 0096 ---")
nombre_y_hora = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y_hora)
print("\n--- Grafica comida (x) Tiempo de cocinado Y ---")
print("\n--- Grafica comida (x) texto a 300 grados ---")
nombre_y_hora.plot.bar(x='name',y='cook_time', rot=30)
plt.title('Comida tipica de india Samuel Martinez NC 0096')
plt.xlabel('Nombre platillo')
plt.ylabel('Tiempo de cocinado')
plt.show()
plt.title('Grafica de varias columnas Samuel Martinez NC 0096')
nombre_y_hora = df_food_india[['name', 'prep_time', 'cook_time']].head(10)
nombre_y_hora.plot.bar(x='name', rot=30)
plt.title('Grafica de 2 columnas Samuel Martinez NC 0096')
plt.xlabel('Nombre platillo')
plt.ylabel('Tiempo de cocinado prep y comida')
plt.show()
print("\n--- Graficas apiladas una tras otra verticalmente 0096 ---")
nombre_y_hora.plot.bar(x='name', stacked=True, rot=30)
plt.title('Graficas apiladas Samuel Martinez NC 0096')
plt.xlabel('Nombre platillo')
plt.ylabel('Tiempo de cocinado prep y comida')
plt.show()
